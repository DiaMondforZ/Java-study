/*数组遍历
* 遍历：逐个取出数组的每一个元素
* 格式：
* for(int i = 0; i < arr.length; i++){
    System.out.println(arr[i]);
}*/
package array;

public class Day31 {
    public static void main(String[] args) {
        int[] arr = {5,15,25,35};
        for (int i = 0; i < arr.length; i++) {
            System.out.println(arr[i]);
        }
    }
}
