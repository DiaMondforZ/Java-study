package basic;

//常用算术运算符：
//        + - * / %
//规则：
//整数相除 / 结果还是整数（舍去小数）
//        % 取余数（取模)
public class Day07 {
    public static void main(String[] args) {
        int a = 10;
        int b = 3;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);
    }
}
