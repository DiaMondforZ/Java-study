//常用比较运算符：== 等于!= 不等于> 大于< 小于>= 大于等于<= 小于等于
//特点：
//运算结果只有 true /false
//判断相等必须用 ==，单个=是赋值
package basic;

public class Day11 {
    public static void main(String[] args) {
        int a = 10;
        int b = 5;
        System.out.println(a>b);
        System.out.println(a==b);
        System.out.println(a!=b);
    }
}
